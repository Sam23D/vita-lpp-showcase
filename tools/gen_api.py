#!/usr/bin/env python3
"""Extract the Lua-visible API of lpp-vita straight from its C sources.

Usage: tools/gen_api.py <path-to-lpp-vita-checkout>

Writes tools/mock/lpp_api.lua, a Lua table describing every module function:
  argc predicate (the exact `if (argc ...) return luaL_error` condition),
  per-argument type checks (luaL_check*/lua_toboolean/table reads),
  whether it pushes return values, and whether it requires unsafe mode.
Also lists every global constant registered by the interpreter.

The mock runtime (tools/mock/lpp_mock.lua) enforces these rules, so the
showcase is checked against the real binding signatures, not the docs.
"""
import re
import sys
from pathlib import Path


def bodies_of(src: str) -> dict:
    out = {}
    for m in re.finditer(r"static int (\w+)\s*\(lua_State \*L\)\s*\{", src):
        i, depth = m.end(), 1
        while depth and i < len(src):
            c = src[i]
            depth += c == "{"
            depth -= c == "}"
            i += 1
        out[m.group(1)] = src[m.end():i]
    return out


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".lpp-vita-src") / "source"
    modules: dict = {}
    consts: list = []
    for f in sorted(root.glob("lua*.cpp")):
        src = f.read_text(errors="ignore")
        bodies = bodies_of(src)
        for m in re.finditer(r"luaL_Reg\s+(\w+)_functions\[\]\s*=\s*\{(.*?)\};", src, re.S):
            mod = m.group(1)
            for name, cfn in re.findall(r'\{\s*"(\w+)"\s*,\s*(\w+)\s*\}', m.group(2)):
                body = bodies.get(cfn, "")
                cond = None
                cm = re.search(r"if\s*\(\s*\(?\s*(argc[^{;]*?)\)\s*\n?\s*return\s+luaL_error", body)
                if cm:
                    cond = cm.group(1).strip().rstrip(")")
                    # normalise "(argc != 3) && (argc != 4" style leftovers
                    cond = cond.replace("(", "").replace(")", "")
                args = {}
                for kind, idx in re.findall(r"luaL_check(integer|number|string|lstring)\s*\(\s*L\s*,\s*(\d+)", body):
                    args.setdefault(int(idx), {"integer": "int", "number": "num", "string": "str", "lstring": "str"}[kind])
                for idx in re.findall(r"lua_toboolean\s*\(\s*L\s*,\s*(\d+)", body):
                    args.setdefault(int(idx), "bool")
                for idx in re.findall(r"lua_(?:rawgeti|objlen)\s*\(\s*L\s*,\s*(\d+)", body):
                    args[int(idx)] = "table"
                pushes = bool(re.search(r"lua_push|lua_newtable", body))
                unsafe = bool(re.search(r"if\s*\(\s*!\s*unsafe_mode\s*\)\s*\n?\s*return\s+luaL_error", body))
                guards = sorted({
                    g for g in re.findall(r'luaL_error\(\s*L\s*,\s*"([^"]+)"', body)
                    if "argument" not in g and "memory block" not in g
                })
                modules.setdefault(mod, {})[name] = (cfn, cond, args, pushes, unsafe, guards)
        consts += re.findall(r"VariableRegister\(\s*\w+\s*,\s*(\w+)\s*\)", src)
    consts = sorted(set(consts) - {"value"})

    lines = ["-- GENERATED by tools/gen_api.py from lpp-vita C sources. Do not edit.", "return {", "  modules = {"]
    total = 0
    for mod in sorted(modules):
        lines.append(f"    {mod} = {{")
        for name in sorted(modules[mod]):
            cfn, cond, args, pushes, unsafe, guards = modules[mod][name]
            total += 1
            arg_s = ", ".join(f"[{i}]={lua_str(t)}" for i, t in sorted(args.items()))
            guard_s = ", ".join(lua_str(g) for g in guards)
            lines.append(
                f"      {name} = {{ c={lua_str(cfn)}, argc={lua_str(cond) if cond else 'nil'}, "
                f"args={{{arg_s}}}, ret={'true' if pushes else 'false'}, unsafe={'true' if unsafe else 'false'}, "
                f"guards={{{guard_s}}} }},"
            )
        lines.append("    },")
    lines.append("  },")
    lines.append("  constants = { " + ", ".join(lua_str(c) for c in consts) + " },")
    lines.append(f"  total = {total},")
    lines.append("}")
    out = Path(__file__).parent / "mock" / "lpp_api.lua"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {len(modules)} modules, {total} functions, {len(consts)} constants")


if __name__ == "__main__":
    main()
